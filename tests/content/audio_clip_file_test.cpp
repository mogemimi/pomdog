/// Appends `value` to `bytes` in little-endian order.
template <typename T>
void appendLittleEndian(std::vector<u8>& bytes, T value)
{
    for (std::size_t i = 0; i < sizeof(T); ++i) {
        bytes.push_back(static_cast<u8>(static_cast<u32>(value) >> (i * 8)));
    }
}

/// Returns a WAV file that holds `samples` as 16-bit stereo PCM at 8000 Hz.
[[nodiscard]] std::vector<u8>
makeStereoWAV(std::span<const i16> samples)
{
    const auto dataSize = static_cast<u32>(samples.size() * sizeof(i16));

    std::vector<u8> bytes = {'R', 'I', 'F', 'F'};
    appendLittleEndian<u32>(bytes, 36 + dataSize);
    bytes.insert(bytes.end(), {'W', 'A', 'V', 'E', 'f', 'm', 't', ' '});
    appendLittleEndian<u32>(bytes, 16);
    appendLittleEndian<u16>(bytes, 1);
    appendLittleEndian<u16>(bytes, 2);
    appendLittleEndian<u32>(bytes, 8000);
    appendLittleEndian<u32>(bytes, 8000 * 4);
    appendLittleEndian<u16>(bytes, 4);
    appendLittleEndian<u16>(bytes, 16);
    bytes.insert(bytes.end(), {'d', 'a', 't', 'a'});
    appendLittleEndian<u32>(bytes, dataSize);
    for (const auto sample : samples) {
        appendLittleEndian<u16>(bytes, static_cast<u16>(sample));
    }
    return bytes;
}

/// TemporaryFile writes bytes to a file in the temporary directory, and removes
/// the file when it goes out of scope.
class TemporaryFile final {
private:
    std::filesystem::path path_;
    std::string directory_;
    std::string name_;

public:
    TemporaryFile(std::string_view name, std::span<const u8> bytes)
        : name_(name)
    {
        auto [tempDir, tempErr] = pomdog::platformfs::getTempDirectoryPath();
        REQUIRE(tempErr == nullptr);
        directory_ = tempDir;
        path_ = std::filesystem::path{tempDir} / name_;

        std::ofstream stream(path_, std::ios::binary | std::ios::trunc);
        REQUIRE(stream.is_open());
        stream.write(reinterpret_cast<const char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
        REQUIRE(stream.good());
    }

    TemporaryFile(const TemporaryFile&) = delete;
    TemporaryFile& operator=(const TemporaryFile&) = delete;
    TemporaryFile(TemporaryFile&&) = delete;
    TemporaryFile& operator=(TemporaryFile&&) = delete;

    ~TemporaryFile()
    {
        std::error_code err;
        std::filesystem::remove(path_, err);
    }

    /// Opens the file through a VFS that mounts the temporary directory.
    [[nodiscard]] std::shared_ptr<File>
    open() const
    {
        auto [ctx, ctxErr] = pomdog::vfs::create();
        REQUIRE(ctxErr == nullptr);
        REQUIRE(pomdog::vfs::mount(ctx, "/tmp", directory_, {.readOnly = true}) == nullptr);

        auto [file, openErr] = pomdog::vfs::open(ctx, "/tmp/" + name_);
        REQUIRE(openErr == nullptr);
        return std::move(file);
    }
};

/// Reads the samples of `clip` until it reaches the end, with a buffer of
/// `bufferSize` bytes. Returns the read bytes and the number of samples per
/// channel that the reads report.
[[nodiscard]] std::tuple<std::vector<u8>, i32>
readAllSamples(AudioClipFile& clip, std::size_t bufferSize)
{
    std::vector<u8> result;
    std::vector<u8> buffer(bufferSize);
    i32 totalSamples = 0;

    const auto bytesPerSample = static_cast<std::size_t>(clip.getBitsPerSample() / 8) *
                                ((clip.getChannels() == AudioChannels::Stereo) ? 2 : 1);

    for (;;) {
        auto [samples, err] = clip.readSamplesInterleaved(buffer);
        REQUIRE(err == nullptr);
        REQUIRE(samples >= 0);
        if (samples == 0) {
            break;
        }
        totalSamples += samples;
        const auto size = static_cast<std::size_t>(samples) * bytesPerSample;
        REQUIRE(size <= buffer.size());
        result.insert(result.end(), buffer.begin(), buffer.begin() + static_cast<std::ptrdiff_t>(size));
    }
    return {std::move(result), totalSamples};
}

